// Compiles contracts/*.sol with solc-js 0.8.28 (via-IR, cancun), the same settings as foundry.toml, into
// out/<Name>.json { abi, bytecode, deployedBytecode }. Used because forge is optional for this package.
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const solc = require("solc");
const root = fileURLToPath(new URL("..", import.meta.url));
const nm = fileURLToPath(new URL("../../../node_modules/", import.meta.url));
const remap: [string, string][] = [
  ["@forshtat/hegota-support/", `${nm}@forshtat/hegota-support/`],
  ["forge-std/", `${nm}forge-std/src/`],
];

const sources: Record<string, { content: string }> = {};
for (const f of readdirSync(`${root}contracts`).filter((f) => f.endsWith(".sol"))) {
  sources[`contracts/${f}`] = { content: readFileSync(`${root}contracts/${f}`, "utf8") };
}

function findImports(path: string) {
  for (const [from, to] of remap) if (path.startsWith(from)) return { contents: readFileSync(to + path.slice(from.length), "utf8") };
  const local = `${root}${path}`;
  if (existsSync(local)) return { contents: readFileSync(local, "utf8") };
  return { error: `not found: ${path}` };
}

const input = {
  language: "Solidity",
  sources,
  settings: {
    viaIR: true,
    evmVersion: "cancun",
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};
const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (out.errors ?? []).filter((e: { severity: string }) => e.severity === "error");
for (const e of out.errors ?? []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);
mkdirSync(`${root}out`, { recursive: true });
for (const [file, contracts] of Object.entries((out.contracts ?? {}) as Record<string, Record<string, any>>)) {
  for (const [name, c] of Object.entries(contracts)) {
    if (!file.startsWith("contracts/") || !c.evm.bytecode.object) continue;
    writeFileSync(`${root}out/${name}.json`, JSON.stringify({ abi: c.abi, bytecode: `0x${c.evm.bytecode.object}`, deployedBytecode: `0x${c.evm.deployedBytecode.object}` }, null, 2));
    console.log(`${file}:${name} ${c.evm.deployedBytecode.object.length / 2} bytes`);
  }
}

// Committed so apps (the web demo deploys an account for a MetaMask owner) never need solc.
const bridge = JSON.parse(readFileSync(`${root}out/BridgeAccount.json`, "utf8"));
mkdirSync(`${root}src/generated`, { recursive: true });
writeFileSync(
  `${root}src/generated/bridgeAccount.ts`,
  `// Generated by scripts/compile.ts (solc 0.8.28, via-IR, cancun). Do not edit.\n` +
    `export const bridgeAccountAbi = ${JSON.stringify(bridge.abi, null, 2)} as const;\n\n` +
    `export const bridgeAccountBytecode = "${bridge.bytecode}" as const;\n`,
);
console.log("wrote src/generated/bridgeAccount.ts");
