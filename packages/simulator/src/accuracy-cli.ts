// Prints the prediction-accuracy table and writes accuracy/RESULTS.md and accuracy/results.json.
//   bun packages/simulator/src/accuracy-cli.ts     (or: bun run accuracy in packages/simulator)
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { runAccuracy, type AccuracyReport } from "./accuracy";

const OUT = new URL("../accuracy/", import.meta.url);

const pct = (a: number, b: number) => (b ? `${((100 * a) / b).toFixed(0)}%` : "n/a");
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const outcomeText = (o: { admitted: boolean; rule?: string }) => (o.admitted ? "admitted" : `rejected (${o.rule})`);
const predictedText = (p: { verdict: string; rule?: string }) => (p.verdict === "admitted" ? "admitted" : `rejected (${p.rule})`);

const METHOD = [
  "Each case is one transaction with two separately captured halves in `packages/core/fixtures`.",
  "The input half is a pre-send `ethrex_simulateFrameTransaction` response (trace included) and the captured stake and reputation reads (`skandha_explorer_listReputation`; an address the page does not list reads as unstaked).",
  "The simulator runs with `createSimulator({ explorer: false, estimate: false })`, so it cannot read the node's admission record or ask the sidecar's estimator. The only node answer it sees is the ethrex simulation.",
  "The held-out half is what a node did with the same transaction: a sidecar send or estimate result, an ethrex send result, or an explorer admission record. Halves are matched by transaction identity (sender, nonce keys, nonce, frames) and by hash, ignoring signatures and fees.",
  "A prediction matches when the admit or reject verdict agrees for that mempool and, for a rejection, the rule agrees. Rule names on both sides come from the same parser (`rules.ts`), so a parser bug would not show up here; the parser has its own tests.",
  "Estimator outcomes that say nothing about the sidecar's rules (placeholder limits, the public gas cap, a missing signature) are dropped, as `check.ts` drops them.",
  "A prediction whose source is `model` comes from our local rule model and no node said it: it is unverified until the sidecar confirms it.",
  "Only transactions with both halves count. Everything else is listed under Excluded. The case count is small because the fixtures were captured to document node behaviour, not to pair pre-send simulations with outcomes.",
].join(" ");

const render = (r: AccuracyReport): string => {
  const t = r.totals;
  const lines: string[] = [];
  lines.push("# Simulator prediction accuracy", "");
  lines.push("Generated by `bun packages/simulator/src/accuracy-cli.ts`. Offline: it replays captured fixtures and sends nothing.", "");
  lines.push("## Counts", "");
  lines.push(`- Cases with both halves: **${t.cases}** (from ${r.scanned} captured calls)`);
  lines.push(`- Comparisons (one per mempool with a held-out outcome): **${t.comparisons}**`);
  lines.push(`- Matched: **${t.matched}** (${pct(t.matched, t.comparisons)})`);
  lines.push(`- Mismatched: **${t.mismatched}**`);
  lines.push(`- Public mempool: ${r.byMempool.public.matched} of ${r.byMempool.public.compared} matched`);
  lines.push(`- Alt mempool: ${r.byMempool.alt.matched} of ${r.byMempool.alt.compared} matched`);
  lines.push(`- Predictions from the local rule model (source \`model\`, unverified): ${t.unverified}, of which ${t.unverifiedMatched} matched`);
  lines.push("");
  lines.push("## Per case", "");
  lines.push("| Case | Mempool | Predicted | Source | Node outcome | Held-out from | Result |", "|---|---|---|---|---|---|---|");
  for (const c of r.cases) {
    for (const x of c.comparisons) {
      lines.push(`| ${cell(c.id)} | ${x.mempool} | ${cell(predictedText(x.predicted))} | ${x.predicted.source}${x.unverified ? " (unverified)" : ""} | ${cell(outcomeText(x.actual))} | ${x.actual.source}: \`${x.actual.file}\` | ${x.judgement === "match" ? "match" : `**mismatch**: ${cell(x.reason ?? "")}`} |`);
    }
  }
  lines.push("");
  lines.push("## Mismatches", "");
  const bad = r.cases.flatMap((c) => c.comparisons.filter((x) => x.judgement === "mismatch").map((x) => ({ c, x })));
  if (!bad.length) lines.push("None.");
  for (const { c, x } of bad) lines.push(`- ${c.id}, ${x.mempool}: ${x.reason}. Node said: ${x.actual.detail ?? "admitted"}`);
  lines.push("");
  lines.push("## Excluded", "");
  lines.push("A fixture is excluded when it lacks the pre-send input or the held-out outcome, or its outcome says nothing.", "");
  lines.push("| Fixture(s) | Reason |", "|---|---|");
  for (const e of r.excluded) lines.push(`| ${e.files.map((f) => `\`${f}\``).join(", ")} | ${cell(e.reason)} |`);
  lines.push("");
  lines.push("## Method", "", METHOD, "");
  return lines.join("\n");
};

const main = async () => {
  const r = await runAccuracy();
  console.log(`${r.totals.cases} cases, ${r.totals.comparisons} comparisons: ${r.totals.matched} matched, ${r.totals.mismatched} mismatched, ${r.totals.unverified} unverified (model) predictions`);
  console.table(r.cases.flatMap((c) => c.comparisons.map((x) => ({
    case: c.id, mempool: x.mempool, predicted: predictedText(x.predicted), source: x.predicted.source, node: outcomeText(x.actual), result: x.judgement,
  }))));
  for (const c of r.cases) for (const x of c.comparisons) if (x.reason) console.log(`mismatch ${c.id} [${x.mempool}]: ${x.reason}`);
  console.log(`${r.excluded.length} fixtures/groups excluded (see RESULTS.md)`);
  mkdirSync(OUT, { recursive: true });
  writeFileSync(new URL("RESULTS.md", OUT), render(r));
  writeFileSync(new URL("results.json", OUT), `${JSON.stringify(r, null, 2)}\n`);
  console.log(`wrote ${fileURLToPath(new URL("RESULTS.md", OUT))} and results.json`);
};

main().catch((e) => { console.error(e); process.exit(1); });
