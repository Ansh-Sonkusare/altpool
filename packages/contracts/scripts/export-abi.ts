// Writes src/generated/abi.ts from forge's out/ so apps never need forge.
import { readFileSync, writeFileSync } from "node:fs";

const { abi } = JSON.parse(readFileSync(new URL("../out/ExitRelay.sol/ExitRelay.json", import.meta.url), "utf8"));
writeFileSync(
  new URL("../src/generated/abi.ts", import.meta.url),
  `// Generated by \`pnpm --filter @altpool/contracts abi\`. Commit it.\nexport const exitRelayAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`exitRelayAbi: ${abi.length} entries`);
