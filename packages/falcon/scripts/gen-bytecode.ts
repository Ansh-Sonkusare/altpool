// Writes src/generated/bytecode.ts (FalconWallet creation code) so the TS side, and browsers, never need forge or fs.
// Source: forge's out/ if built, else the deployed factory's own code, which embeds the exact creation code it CREATE2s.
// Either way the result is checked against factory.predictAddress on the live devnet before it is written.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { concatHex, encodeAbiParameters, getContractAddress, keccak256, parseAbi, type Address, type Hex } from "viem";
import { pub, readDeployments } from "./lib";

const { factory, verifier } = readDeployments();
if (!factory || !verifier) throw new Error("deployments.json needs factory and verifier");
const salt = keccak256("0x1234");
const want = await pub.readContract({ address: factory, abi: parseAbi(["function predictAddress(bytes32) view returns (address)"]), functionName: "predictAddress", args: [salt] });
const args = encodeAbiParameters([{ type: "address" }, { type: "bytes32" }], [verifier, salt]);
const matches = (init: Hex) =>
  getContractAddress({ opcode: "CREATE2", from: factory as Address, salt, bytecodeHash: keccak256(concatHex([init, args])) }).toLowerCase() === want.toLowerCase();

let init: Hex | undefined;
let source = "";
const art = new URL("../out/FalconWallet.sol/FalconWallet.json", import.meta.url);
if (existsSync(art)) {
  const c = JSON.parse(readFileSync(art, "utf8")).bytecode.object as Hex;
  if (matches(c)) [init, source] = [c, "forge out/"];
  else console.log("out/FalconWallet differs from the deployed factory's wallet; falling back to the factory's code");
}
if (!init) {
  // The creation code ends at its runtime's CBOR metadata (solc 0.8.x); its start has no fixed prologue (the
  // HegotaSupport constructor comes first), so every start is tried against each metadata end.
  const code = (await pub.getCode({ address: factory }))!.slice(2);
  const ends = [...code.matchAll(/64736f6c6343[0-9a-f]{6}0033/g)].map((m) => m.index! + m[0].length).filter((i) => i % 2 === 0);
  for (const e of ends) for (let s = 0; !init && s < e; s += 2) if (matches(`0x${code.slice(s, e)}`)) [init, source] = [`0x${code.slice(s, e)}`, `factory ${factory} code`];
}
if (!init) throw new Error("no creation code reproduces factory.predictAddress");

mkdirSync(new URL("../src/generated", import.meta.url), { recursive: true });
writeFileSync(
  new URL("../src/generated/bytecode.ts", import.meta.url),
  `// Generated by \`bun run --filter @altpool/falcon bytecode\` (from ${source}); checked against factory.predictAddress. Commit it.\n` +
    `export const falconWalletCreationCode = "${init}" as const;\n`,
);
console.log(`falconWalletCreationCode: ${(init.length - 2) / 2} bytes from ${source}, reproduces predictAddress on ${factory}`);
